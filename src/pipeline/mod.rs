/// The default largest frame: 16 MiB. The single source of truth for the
/// frame/event byte cap (`proto::framing::DEFAULT_MAX_FRAME_BYTES` and
/// `client::transport::sse::DEFAULT_MAX_EVENT_BYTES` alias it).
pub(crate) const DEFAULT_MAX_FRAME_BYTES: usize = 16 * 1024 * 1024;

/// Tables larger than this (in slots) are dropped, not cleared, when the run
/// that just used them held far fewer entries. Clearing a non-empty hash
/// table costs O(capacity), so reusing a peak-sized table for many small
/// runs would make total cost O(peak x runs). Mirrors `SCRATCH_KEEP`.
pub(crate) const RETAIN_FLOOR: usize = 1024;

/// The estimated resident heap of an `Arc<str>` id of `len` bytes: the two
/// reference counts plus the text, in 16-byte allocation classes. What a
/// pipeline stage charges to the history budget for an id it keeps
/// (docs/DECISIONS.md D25).
pub(crate) fn id_heap(len: usize) -> usize {
    crate::json::text_bytes(len.saturating_add(16))
}

/// A 64-bit fingerprint of `text`, for comparing a peer's repeated field
/// against an earlier value without keeping a copy. The hash keys are drawn
/// at random once per process, so a peer cannot compute collisions offline
/// and two different strings match with negligible probability (D25).
pub(crate) fn fingerprint(text: &str) -> u64 {
    use std::hash::BuildHasher as _;
    static KEYS: std::sync::OnceLock<std::collections::hash_map::RandomState> =
        std::sync::OnceLock::new();
    KEYS.get_or_init(std::collections::hash_map::RandomState::new)
        .hash_one(text)
}

/// The heap of an optional id (an owner): nothing for `None`.
pub(crate) fn owner_heap(owner: Option<&crate::ids::SubagentRunId>) -> usize {
    owner.map_or(0, |id| id_heap(id.as_str().len()))
}

/// The estimated resident bytes of one hash-table entry of `entry` bytes
/// (key plus value): the entry and its control byte, doubled for the
/// table's load factor (a hash table holds between 7/16 and 7/8 of its
/// buckets, so a fixed factor of 2 lies within about 0.9x to 1.45x of a
/// table's actual size) (D25).
pub(crate) const fn table_slot(entry: usize) -> usize {
    (entry + 1) * 2
}

/// Whether a table of `capacity` slots holding `len` entries is oversized.
fn oversized(capacity: usize, len: usize) -> bool {
    capacity > RETAIN_FLOOR && capacity / 4 > len
}

/// Empties `map` for reuse by the next run: cleared (keeping its capacity)
/// unless it is far larger than the run that used it, then replaced.
pub(crate) fn reset_map<K, V>(map: &mut std::collections::HashMap<K, V>) {
    if oversized(map.capacity(), map.len()) {
        *map = std::collections::HashMap::new();
    } else {
        map.clear();
    }
}

/// [`reset_map`] for sets.
pub(crate) fn reset_set<T>(set: &mut std::collections::HashSet<T>) {
    if oversized(set.capacity(), set.len()) {
        *set = std::collections::HashSet::new();
    } else {
        set.clear();
    }
}

/// Resource budgets. Every limit is configurable; defaults are documented on
/// [`Limits::default`].
///
/// # Memory, and large state
///
/// The defaults keep worst-case resident client memory for one stream near
/// 252 MiB (64-bit; docs/DECISIONS.md D14): about 124 MiB of state and
/// patched activity content ([`PatchLimits::max_nodes`]) plus 128 MiB of
/// history and id bookkeeping growth
/// ([`max_history_bytes`](Limits::max_history_bytes)). An
/// application whose state or history is larger raises the limit it needs,
/// and pays for it as follows:
///
/// - [`PatchLimits::max_nodes`] (in `patch`): each extra node unit may hold
///   up to about 720 bytes in the worst shape (about 140 bytes for objects
///   with short keys, 32 bytes for a scalar array element), so 1,000,000
///   units allow up to about 690 MiB of state. The per-patch walk budget is
///   unchanged by the ceiling, but it scales with the document, so a larger
///   document also makes each patch against it allowed more work. To admit
///   a `STATE_SNAPSHOT` of the new size, raise
///   [`max_container_entries`](Limits::max_container_entries) too (each
///   entry may cost up to about 720 bytes while the event is parsed, and the
///   limit also bounds server input admission, `validate_*` and the protobuf
///   decode budget), keeping it below `max_nodes` so a snapshot at the entry
///   limit still takes growing deltas.
/// - [`max_history_bytes`](Limits::max_history_bytes): each extra byte is
///   about one more byte of resident history (the estimate stays within
///   0.9x to 1.4x of what is allocated). `usize::MAX` disables it; the
///   reconcile work bound still applies.
///
/// Diagnostics are bounded per event
/// ([`max_diagnostics_per_event`](Limits::max_diagnostics_per_event)) and
/// in the client report
/// ([`max_report_diagnostics`](Limits::max_report_diagnostics)), not per
/// stream: their volume over a stream is linear in the input, which the
/// limits above already bound, and a per-stream cap would hide every later
/// problem (docs/DECISIONS.md D21).
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
#[non_exhaustive]
pub struct Limits {
    /// Largest accepted frame (SSE event data or protobuf frame), in bytes.
    pub max_frame_bytes: usize,
    /// Largest number of container entries (object members plus array
    /// elements) in one event. An entry costs from 32 bytes to about 720
    /// bytes once parsed (see [`PatchLimits::max_nodes`]), so this bounds the
    /// memory one event, a `STATE_SNAPSHOT` included, can take. Below the
    /// patch ceiling by default, so a structure-only snapshot at this limit
    /// still takes growing deltas; a snapshot whose text adds more node units
    /// than the headroom left can sit above the ceiling, and then any delta
    /// that grows it ends the stream. Server input admission and
    /// `validate_*` use the same limit.
    pub max_container_entries: usize,
    /// Deepest accepted JSON nesting in one event. Events decoded from the
    /// protobuf wire are additionally bounded at 128 levels (the codec's
    /// stack-safe ceiling) whatever this is set to.
    pub max_depth: usize,
    /// JSON Patch limits for state and activity content.
    pub patch: PatchLimits,
    /// Diagnostics per event before a summary replaces the rest. There is no
    /// per-stream cap on what the sink receives (docs/DECISIONS.md D21).
    pub max_diagnostics_per_event: usize,
    /// Diagnostics a client run's report keeps before one summary replaces
    /// the rest (client runs only; the sink and observers still see every
    /// one). Unlike `max_diagnostics_per_event`, `0` is accepted and keeps
    /// only the summary.
    pub max_report_diagnostics: usize,
    /// The most the held message history may grow by over one stream, as
    /// estimated resident bytes: the `serde_json` tree of activity content
    /// and metadata (value slots, map nodes, string heaps rounded to 16
    /// bytes), text and arguments at their length, plus about 280 bytes per
    /// held message and call (its slot, index entries and id copies).
    ///
    /// The same budget also covers the ids the pipeline keeps to check and
    /// track the stream, whether or not a held message carries them: open
    /// steps, reasoning spans, subagent invocations, the run's item and
    /// tool-call tables, the message ids the thread has used (kept after a
    /// snapshot drops the message, so a later result cannot reuse one), and
    /// the copies of the tool calls a run ends with pending, charged until
    /// the next run starts (docs/DECISIONS.md D25). Those charges land on
    /// the event that makes them, so a run whose pending calls cross the
    /// limit ends with `LimitExceeded` on its `RUN_FINISHED`. Each table
    /// entry is charged at twice its size (hash-table load), and an id
    /// shared by several stages once per stage, which over-states long ids.
    ///
    /// The estimate stays within 0.9x to 1.4x of the bytes actually allocated for
    /// maps, messages, calls, content parts and that bookkeeping
    /// (`tests/history_resident.rs`).
    /// Large parsed arrays (down to about 0.7x) and, with `preserve-order`,
    /// objects grown member by member (down to about 0.75x) also allocate
    /// capacity slack the estimate leaves out: the untouched tail of a large
    /// block is not resident. Streamed text is charged at its length, without
    /// its `String`'s capacity slack. Exceeding the limit
    /// ends the stream with [`ErrorCode::LimitExceeded`](crate::ErrorCode).
    /// Growth is net of what snapshots replace or drop, and is counted from
    /// the history the processor started with, so a restored thread that is
    /// already large streams normally. Metadata merges and activity patches
    /// are credited for the values they overwrite (activity patches only
    /// for the part measurable within a bound proportional to the patch,
    /// and never for array shifts), so updating in place is not growth.
    /// `usize::MAX` disables this limit. Raising it for a large history
    /// costs about one resident byte per byte raised (see [`Limits`],
    /// "Memory, and large state").
    ///
    /// A second, separate bound also ends a stream with `LimitExceeded`, and
    /// still applies when this limit is disabled: the **reconcile work
    /// bound**. A `MESSAGES_SNAPSHOT` that drops held messages walks back
    /// from the end of the history to the first one it drops. That walk is
    /// paid from a work bank. The bank starts at about one million steps
    /// plus eight per message already held, and gains eight steps per
    /// message a snapshot restates or the stream pushes. A snapshot whose
    /// drops would walk past what the bank holds is not applied at all, is
    /// reported as `snapshot.work_bound`, and the [`Processor`] then ends the
    /// stream. A [`Reducer`](reduce::Reducer) driven directly keeps its
    /// history unchanged (none of the snapshot is applied) and reports the
    /// diagnostic. This bound is not configurable. It keeps the total
    /// reconcile work linear in the input: without it, repeated small
    /// snapshots that drop messages behind a long held tail would cost
    /// O(held history) each.
    pub max_history_bytes: usize,
}

impl Default for Limits {
    /// 16 MiB frames, 150,000 container entries, depth 128, default patch
    /// limits, 256 diagnostics per event, 4096 diagnostics per client report,
    /// 128 MiB of history and id bookkeeping growth.
    ///
    /// Together these keep what one stream makes the client hold near
    /// 252 MiB (64-bit; docs/DECISIONS.md D14): at most about 124 MiB of
    /// state and patched activity content (the patch ceiling), plus at most
    /// 128 MiB of history and id bookkeeping growth as estimated. Not
    /// included: the event being
    /// parsed (at most 150,000 entries, about 103 MiB in the worst shape, plus
    /// its text; a chunk that opens an item holds its metadata twice while it
    /// is expanded, on the synthesized start and first content, so up to
    /// about twice that), the one event that crosses the history limit, and history
    /// restored with [`Processor::with_history`] or kept by a
    /// [`Thread`][crate::client::Thread] across runs, which is the host's to
    /// trim.
    #[cfg_attr(
        not(feature = "client"),
        doc = "",
        doc = "[crate::client::Thread]: https://docs.rs/agui-sdk/latest/agui_sdk/client/struct.Thread.html"
    )]
    fn default() -> Self {
        Limits {
            max_frame_bytes: DEFAULT_MAX_FRAME_BYTES,
            max_container_entries: 150_000,
            max_depth: 128,
            patch: PatchLimits::default(),
            max_diagnostics_per_event: crate::diagnostics::DEFAULT_MAX_PER_EVENT,
            max_report_diagnostics: 4096,
            max_history_bytes: 128 * 1024 * 1024,
        }
    }
}

