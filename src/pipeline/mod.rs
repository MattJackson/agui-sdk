//! The consumer processing pipeline, sans-IO.
//!
//! The spec fixes the order every received event goes through
//! (`basic/processing.mdx`, ARCH-01, PROC-21, PROC-22, PROC-28):
//!
//! ```text
//!  frame ─▶ compatibility boundary ─▶ middleware ─▶ enforcement ─▶ chunk expansion ─▶ verification ─▶ reducer ─▶ application
//!          (compat)                   (client)      (enforce)      (chunks)           (verify)         (reduce)
//! ```
//!
//! This module provides each stage as a plain synchronous state machine, with
//! no runtime and no I/O, and two compositions:
//!
//! * [`compat::Boundary`] and [`compat::EraShims`]: the stages before
//!   middleware.
//! * [`Processor`]: everything after middleware (enforcement through the
//!   reducer). It also owns a boundary and, for a pinned legacy peer, the era
//!   shims, so its no-middleware fast path ([`Processor::push_json`]) runs
//!   the whole pipeline.
//!
//! The async [`client`][crate::client] wires transport → boundary → shims →
//! [`client::middleware`][crate::client::middleware] → processor
//! ([`Processor::push_value`]). Custom hosts (a WebSocket bridge, a recorded
//! stream checker) can do the same, and get the same verdicts, because the
//! verdicts live here, not in a transport (PROC-06, PROC-07, PB-13).
//!
//! # Hot path
//!
//! With no middleware installed, a frame goes from bytes to a typed,
//! enforced [`Event`] in one parse ([`Processor::push_json`]): the
//! compatibility rules and the generated shape table are applied while
//! deserializing, so no intermediate `serde_json::Value` is built. Frames the
//! boundary may need to rewrite (a retired `THINKING_*` event, legacy binary
//! content, an optional `null`, any of them however JSON spells it) and every
//! frame from an era-pinned peer are detected by a scan of the bytes and
//! routed through the boundary as a `Value` internally, and every
//! `RUN_STARTED` reaches the boundary's per-run state, so the fast path and
//! the middleware path give identical verdicts (VER-13, VER-14, VER-30). Installing
//! middleware moves a frame through a `Value` once (middleware must see raw
//! material, PROC-29) and the processor then enforces that `Value` in place.
//! Chunk expansion and verification are O(1) per event with no allocation
//! beyond the ids they track; the reducer is O(delta). Output goes into a
//! caller-owned `Vec` so its capacity is reused across events.
//!
//! Public items here are building blocks: stable, documented, but most
//! applications never touch them.
#![cfg_attr(
    not(feature = "client"),
    doc = "",
    doc = "[crate::client]: https://docs.rs/agui-sdk/latest/agui_sdk/client/index.html"
)]
#![cfg_attr(
    not(feature = "client"),
    doc = "",
    doc = "[crate::client::middleware]: https://docs.rs/agui-sdk/latest/agui_sdk/client/middleware/index.html"
)]

