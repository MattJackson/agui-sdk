    /// Every pattern, alone and inside fillers that trip the flags, at every
    /// offset across two words, with every frame length around it.
    #[test]
    fn needs_boundary_matches_the_oracle_at_every_offset() {
        let patterns: &[&[u8]] = &[
            b"THINKING_",
            b"\"binary\"",
            b":null",
            b": \t\r\nnull",
            b"x null",
            b"\\u0040",
            b"\\u007F",
            b"\\u0080",
            b"\\u003F",
            b"nunull",
            b"nnull",
        ];
        for pattern in patterns {
            for &fill in b"xKyn u\\:J]ot\x00\x01\x80\xff" {
                for before in 0..20 {
                    for after in 0..10 {
                        let mut frame = vec![fill; before];
                        frame.extend_from_slice(pattern);
                        frame.extend(std::iter::repeat(fill).take(after));
                        agree(&frame);
                        // The pattern cut short at the end of the frame.
                        for cut in 0..pattern.len() {
                            agree(&frame[..before + cut]);
                        }
                    }
                }
            }
        }
    }

    /// Every string of up to five bytes over the patterns' alphabet, behind
    /// every prefix length that puts it across a word boundary.
