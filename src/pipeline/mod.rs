    /// different, under keys a peer cannot know: not std's fixed
    /// `DefaultHasher::new()` keys, which anyone can compute collisions for.
    #[test]
    fn fingerprints_are_stable_and_keyed_per_process() {
        use std::hash::{Hash, Hasher};
        assert_eq!(
            super::fingerprint("parent-a"),
            super::fingerprint("parent-a")
        );
        assert_ne!(
            super::fingerprint("parent-a"),
            super::fingerprint("parent-b")
        );
        assert_ne!(super::fingerprint(""), super::fingerprint("parent-a"));
        let public = |text: &str| {
            let mut hasher = std::collections::hash_map::DefaultHasher::new();
            text.hash(&mut hasher);
            hasher.finish()
        };
        for text in ["", "parent-a", "toolCallName"] {
            assert_ne!(super::fingerprint(text), public(text), "{text:?}");
        }
    }

