/// Enforcement, chunk expansion, verification and the reducer, composed.
///
/// One processor per stream (or per [`Thread`][crate::client::Thread], which
/// carries history across runs: [`Processor::with_history`]).
///
/// Every event goes through the stages in the order `basic/processing.mdx`
/// fixes (ARCH-01, PROC-21, PROC-28): enforcement strips and rejects, chunk
/// expansion turns shorthand into start/content/end, verification judges
/// the expanded events, and only then does the reducer apply them. An event
/// the verifier refuses never reaches the reducer, so history holds exactly
/// what was delivered before the failure (LIFE-19). The one exception is
/// the history limit ([`Limits::max_history_bytes`]): the reducer judges it
/// after applying an event, so when it ends the stream, history also holds
/// the effect of the event that crossed it, which was not delivered.
///
/// After an `Err` the processor is spent: every later call fails with the
/// same code, so a host cannot continue a stream the pipeline rejected.
///
/// Feeding a recorded or custom-transport stream through it:
///
/// ```
/// use std::sync::Arc;
///
/// use agui_sdk::diagnostics::{CollectingSink, Reporter};
/// use agui_sdk::pipeline::{PipelineConfig, Processor, Termination};
///
/// let frames: [&[u8]; 4] = [
///     br#"{"type":"RUN_STARTED","threadId":"t-1","runId":"r-1"}"#,
///     br#"{"type":"TEXT_MESSAGE_CHUNK","messageId":"m1","role":"assistant","delta":"Hi"}"#,
///     br#"{"type":"STATE_SNAPSHOT","snapshot":{"step":1},"futureField":true}"#,
///     br#"{"type":"RUN_FINISHED","threadId":"t-1","runId":"r-1"}"#,
/// ];
///
/// let sink = Arc::new(CollectingSink::default());
/// let mut reporter = Reporter::new(sink.clone(), 16);
/// let mut processor = Processor::new(PipelineConfig::default());
/// let mut out = Vec::new();
/// for frame in frames {
///     processor.push_json(frame, &mut reporter, &mut out)?;
/// }
/// assert_eq!(processor.finish(), Termination::Complete);
///
/// // The chunk arrived expanded into start/content/end, so 6 events in all.
/// assert_eq!(out.len(), 6);
/// assert_eq!(processor.reducer().messages().len(), 1);
/// assert_eq!(processor.reducer().state()["step"], 1);
/// // The unknown member was stripped, with a warning (PROC-17).
/// assert!(!sink.take().is_empty());
/// # Ok::<(), agui_sdk::Error>(())
/// ```
#[cfg_attr(
    not(feature = "client"),
    doc = "",
    doc = "[crate::client::Thread]: https://docs.rs/agui-sdk/latest/agui_sdk/client/struct.Thread.html"
)]
#[derive(Debug)]
pub struct Processor {
    /// The compatibility boundary for [`push_json`](Self::push_json) frames
    /// that carry a retired shape. Hosts using [`push_value`](Self::push_value)
    /// run their own boundary before middleware.
    boundary: compat::Boundary,
    /// Era shims for a pinned legacy peer, on the `push_json` path.
    era: Option<compat::EraShims>,
    enforcer: enforce::Enforcer,
    chunks: chunks::ChunkExpander,
    verifier: verify::ConsumerVerifier,
    reducer: reduce::Reducer,
    scratch: Vec<Event>,
    /// The code of the fatal verdict that ended the stream, if any.
    failed: Option<crate::error::ErrorCode>,
    /// What a boundary outside this processor (the client's, for parsed
    /// frames) keeps under peer-chosen ids, charged with the rest (D28).
    external_bookkeeping: usize,
}

/// Byte patterns that mark a frame the compatibility boundary may need to
/// rewrite: a retired `THINKING_*` event type, or legacy binary content.
const RETIRED_THINKING: &[u8] = b"THINKING_";
const RETIRED_BINARY: &[u8] = b"\"binary\"";

/// Whether the compatibility boundary may have something to do with this
/// frame, judged from its bytes alone. It over-approximates, never under:
/// a frame that merely looks like one takes the boundary's `Value` route and
/// gets the verdict it would have got anyway, while a frame the boundary
/// must see is never missed (PROC-22, PROC-06). Besides the plain spellings
/// of the retired shapes, that means:
///
/// * any member whose value is `null`, because the registry's optional
///   nulls are the boundary's to read as absent, noticed once per run like
///   on every other path (BASIC-12);
/// * any `\u` escape of an ASCII letter or `_`, because JSON may spell
///   `THINKING_START` or `binary` that way and the parsed name is what counts.
///
/// One pass, eight bytes a step. A step stops only at a byte that can anchor
/// one of the patterns, and [`boundary_at`] then checks that pattern in
/// place: a `K` (the fifth byte of `THINKING_`), a `y` (the seventh of
/// `"binary"`), a `\` (an escape), or an `n` followed by `u` (a `null`).
/// These are rare next to the quotes and capitals every frame is full of.
fn needs_boundary(frame: &[u8]) -> bool {
    const ONES: u64 = 0x0101_0101_0101_0101;
    const HIGH: u64 = 0x8080_8080_8080_8080;
    // The high bit of every byte of `x` equal to `b`. A false flag (borrow)
    // only ever sits above a true one, and every flag is checked against the
    // frame anyway, so nothing is missed.
    let eq = |x: u64, b: u8| {
        let v = x ^ (ONES * u64::from(b));
        v.wrapping_sub(ONES) & !v & HIGH
    };
    let mut i = 0;
    while let Some(word) = frame.get(i..i + 8) {
        let Ok(word) = <[u8; 8]>::try_from(word) else {
            break;
        };
        let x = u64::from_le_bytes(word);
        // An `n` counts when the next byte is a `u`, or lies in the next word.
        let null = eq(x, b'n') & ((eq(x, b'u') >> 8) | 1 << 63);
        let mut found = eq(x, b'K') | eq(x, b'y') | eq(x, b'\\') | null;
        while found != 0 {
            let at = i + (found.trailing_zeros() / 8) as usize;
            if boundary_at(frame, at) {
                return true;
            }
            found &= found - 1;
        }
        i += 8;
    }
    (i..frame.len()).any(|at| boundary_at(frame, at))
}

/// Whether the frame's bytes contain `REASONING_END` (a `\u` spelling of it
/// already routes the frame through [`needs_boundary`]). Checked only while
/// the boundary tracks a translated span, so its 1.0 end reaches the
/// boundary and closes it there (D28).
fn names_reasoning_end(frame: &[u8]) -> bool {
    frame.windows(13).any(|w| w == b"REASONING_END")
}

/// Whether one of [`needs_boundary`]'s patterns is anchored at `frame[at]`:
/// a retired marker through it, a member `null` (after a `:`, whitespace
/// between allowed) or a `\u00XX` escape for a code point in `0x40..=0x7F`
/// (letters, `_`) starting at it.
fn boundary_at(frame: &[u8], at: usize) -> bool {
    let starts = |back: usize, marker: &[u8]| {
        at.checked_sub(back)
            .and_then(|start| frame.get(start..))
            .is_some_and(|tail| tail.starts_with(marker))
    };
    match frame[at] {
        b'K' => starts(4, RETIRED_THINKING),
        b'y' => starts(6, RETIRED_BINARY),
        b'\\' => matches!(
            frame.get(at..at + 5),
            Some([b'\\', b'u', b'0', b'0', b'4'..=b'7'])
        ),
        // Each whitespace run is walked back over by at most the one `null`
        // right after it, so the walks stay linear in the frame.
        b'n' => {
            starts(0, b"null")
                && frame[..at]
                    .iter()
                    .rev()
                    .find(|b| !matches!(b, b' ' | b'\t' | b'\n' | b'\r'))
                    == Some(&b':')
        }
        _ => false,
    }
}

/// The three separate scans [`needs_boundary`] replaced, kept as its oracle.
#[cfg(test)]
mod oracle {
    use super::{RETIRED_BINARY, RETIRED_THINKING};

    /// [`needs_boundary`](super::needs_boundary) as three passes.
    pub(super) fn needs_boundary(frame: &[u8]) -> bool {
        has_retired_marker(frame) || has_member_null(frame) || has_escaped_name_char(frame)
    }

    /// Whether `frame` contains either retired marker. One pass, eight bytes a
    /// step, that stops only at a `K` (the fifth byte of `THINKING_`) or a `y`
    /// (the seventh of `"binary"`) and then compares the marker in place; both
    /// are rare next to the quotes and capitals every frame is full of.
    pub(super) fn has_retired_marker(frame: &[u8]) -> bool {
        const ONES: u64 = 0x0101_0101_0101_0101;
        const HIGH: u64 = 0x8080_8080_8080_8080;
        let at_marker = |i: usize| {
            let starts = |back: usize, marker: &[u8]| {
                i.checked_sub(back)
                    .and_then(|start| frame.get(start..))
                    .is_some_and(|tail| tail.starts_with(marker))
            };
            match frame[i] {
                b'K' => starts(4, RETIRED_THINKING),
                _ => starts(6, RETIRED_BINARY),
            }
        };
        let mut i = 0;
        while let Some(word) = frame.get(i..i + 8) {
            let Ok(word) = <[u8; 8]>::try_from(word) else {
                break;
            };
            let x = u64::from_le_bytes(word);
            let k = x ^ (ONES * u64::from(b'K'));
            let y = x ^ (ONES * u64::from(b'y'));
            let mut found = ((k.wrapping_sub(ONES) & !k) | (y.wrapping_sub(ONES) & !y)) & HIGH;
            while found != 0 {
                // A false flag (borrow) only ever sits above a true one, and
                // every flag is checked against the frame anyway.
                let at = i + (found.trailing_zeros() / 8) as usize;
                if matches!(frame[at], b'K' | b'y') && at_marker(at) {
                    return true;
                }
                found &= found - 1;
            }
            i += 8;
        }
        (i..frame.len()).any(|at| matches!(frame[at], b'K' | b'y') && at_marker(at))
    }

    /// A `null` literal after a `:` (whitespace between allowed).
    fn has_member_null(frame: &[u8]) -> bool {
        frame.windows(4).enumerate().any(|(at, window)| {
            window == b"null"
                && frame[..at]
                    .iter()
                    .rev()
                    .find(|b| !matches!(b, b' ' | b'\t' | b'\n' | b'\r'))
                    == Some(&b':')
        })
    }

    /// A `\u00XX` escape for a code point in `0x40..=0x7F` (letters, `_`).
    fn has_escaped_name_char(frame: &[u8]) -> bool {
        frame.windows(5).any(|w| {
            w[0] == b'\\'
                && w[1] == b'u'
                && w[2] == b'0'
                && w[3] == b'0'
                && matches!(w[4], b'4'..=b'7')
        })
    }
}

impl Processor {
    /// A processor for a fresh thread: no history, state `{}`.
    #[must_use]
    pub fn new(config: PipelineConfig) -> Self {
        Self::with_reducer(
            config,
            verify::ConsumerVerifier::new(),
            reduce::Reducer::new(),
        )
    }

    /// A processor continuing a thread: deltas apply to `state` and history
    /// accumulates onto `messages` (STATE-10, LIFE-45, INTR-16).
    ///
    /// The history's message ids are known to the verifier, so the stream
    /// cannot mint a new message under one of them (BASIC-15).
    #[must_use]
    pub fn with_history(config: PipelineConfig, messages: Vec<Message>, state: Value) -> Self {
        let verifier = verify::ConsumerVerifier::new()
            .with_known_messages(messages.iter().map(|m| m.id().clone()));
        Self::with_reducer(
            config,
            verifier,
            reduce::Reducer::with_history(messages, state),
        )
    }

    fn with_reducer(
        config: PipelineConfig,
        verifier: verify::ConsumerVerifier,
        mut reducer: reduce::Reducer,
    ) -> Self {
        let defaults = Limits::default();
        if config.limits.patch != defaults.patch
            || config.limits.max_history_bytes != defaults.max_history_bytes
        {
            reducer.set_limits(&config.limits);
        }
        Processor {
            boundary: compat::Boundary::default(),
            era: config.legacy_peer.map(compat::EraShims::new),
            enforcer: enforce::Enforcer::new(config.limits),
            chunks: chunks::ChunkExpander::new(),
            verifier,
            reducer,
            scratch: Vec::new(),
            failed: None,
            external_bookkeeping: 0,
        }
    }

    /// Expects the stream to carry the run `run_id` on `thread_id`: a run
    /// boundary naming another thread, or a `RUN_FINISHED` naming another run
    /// than its `RUN_STARTED`, is a `verify.identity` error (RUNIN-04,
    /// RUNIN-05), and so, at [`finish_checked`](Self::finish_checked), is a
    /// stream on which the requested run never appeared (RUNIN-06). Other
    /// runs may come before or after it. The client sets this from the
    /// request; a custom host checking a recorded stream may leave it unset.
    #[must_use]
    pub fn expecting(mut self, thread_id: ThreadId, run_id: RunId) -> Self {
        self.verifier.set_expected(thread_id, run_id);
        self
    }

    /// Fast path: one raw frame (a JSON event object as bytes) through the
    /// compatibility boundary, the era shims (when a legacy peer is pinned),
    /// enforcement, expansion, verification and the reducer. Appends zero or
    /// more [`Processed`] to `out` (zero for a dropped event, several for an
    /// expanded chunk). Use this only when no middleware is installed.
    ///
    /// A frame that may carry a retired shape (a `THINKING_*` type, legacy
    /// binary content, an optional `null`), and every frame from a pinned
    /// legacy peer, first goes
    /// through the compatibility boundary and era shims as a JSON value, so
    /// the pipeline order holds on this path too (PROC-22, VER-14). Every
    /// other frame is parsed once, straight into a typed event.
    ///
    /// # Errors
    ///
    /// A fatal verdict (malformed known value, streaming violation). The
    /// processor must not be fed again after an error.
    pub fn push_json(
        &mut self,
        frame: &[u8],
        reporter: &mut Reporter,
        out: &mut Vec<Processed>,
    ) -> Result<()> {
        self.check_live()?;
        let enforced = if self.era.is_some()
            || needs_boundary(frame)
            || (self.boundary.tracks_spans() && names_reasoning_end(frame))
        {
            self.upgrade_and_enforce(frame, reporter)
        } else {
            let enforced = self.enforcer.enforce_event_json(frame, reporter);
            // The boundary did not see this frame, but its per-run state
            // (the names it mints, the notices it gave) must still follow
            // the runs, as it does on every other path.
            if let Ok(Some(Event::RunStarted(started))) = &enforced {
                self.boundary.run_started(Some(started.run_id.as_str()));
            }
            enforced
        };
        self.finish_push(enforced, reporter, out)
    }

    fn upgrade_and_enforce(
        &mut self,
        frame: &[u8],
        reporter: &mut Reporter,
    ) -> Result<Option<Event>> {
        // Budgets apply while the tree is built, not after (a marker can
        // be anywhere in a frame, so this path is the peer's to choose).
        let mut value = self.enforcer.parse_frame(frame)?;
        if !self.boundary.upgrade(&mut value, reporter) {
            return Ok(None);
        }
        if let Some(shims) = &self.era {
            if !shims.upgrade_event(&mut value, reporter) {
                return Ok(None);
            }
        }
        self.enforcer.enforce_event_value(value, reporter)
    }

    /// Middleware path: one frame that has *already* been through the
    /// compatibility boundary, the era shims and middleware. The caller owns
    /// those stages on this path (run them with [`compat::Boundary::upgrade`]
    /// and [`compat::EraShims::upgrade_event`]); this processor's own
    /// boundary is not applied again. Enforced in place, without
    /// re-serializing.
    ///
    /// # Errors
    ///
    /// As [`push_json`](Self::push_json).
    pub fn push_value(
        &mut self,
        frame: Value,
        reporter: &mut Reporter,
        out: &mut Vec<Processed>,
    ) -> Result<()> {
        self.check_live()?;
        let enforced = self.enforcer.enforce_event_value(frame, reporter);
        self.finish_push(enforced, reporter, out)
    }

    fn check_live(&self) -> Result<()> {
        match self.failed {
            None => Ok(()),
            Some(code) => Err(crate::error::Error::new(
                code,
                "the stream was already rejected; the processor cannot continue it",
            )),
        }
    }

    /// Expansion, verification and the reducer for one enforced event, then
    /// the end of the event's diagnostics budget.
    fn finish_push(
        &mut self,
        enforced: Result<Option<Event>>,
        reporter: &mut Reporter,
        out: &mut Vec<Processed>,
    ) -> Result<()> {
        let result = match enforced {
            Ok(Some(event)) => {
                let event_type = event.event_type();
                let result = self.expand_verify_apply(event, reporter, out);
                reporter.end_event(Some(event_type.as_str()));
                result
            }
            Ok(None) => {
                reporter.end_event(None);
                Ok(())
            }
            Err(err) => {
                reporter.end_event(None);
                Err(err)
            }
        };
        if let Err(err) = &result {
            self.failed = Some(err.code());
        }
        result
    }

    fn expand_verify_apply(
        &mut self,
        event: Event,
        reporter: &mut Reporter,
        out: &mut Vec<Processed>,
    ) -> Result<()> {
        self.scratch.clear();
        self.chunks.push(event, &mut self.scratch)?;
        for event in self.scratch.drain(..) {
            self.verifier.observe(&event)?;
            // What the verifier keeps under peer-chosen ids is charged to
            // the history budget (D25), with what this processor's boundary
            // and a host's (`charge_boundary`) keep (D28); the reducer's
            // check below ends the stream when it is crossed.
            self.reducer.set_bookkeeping(
                self.verifier
                    .retained()
                    .saturating_add(self.boundary.retained())
                    .saturating_add(self.external_bookkeeping),
            );
            if let Event::RunStarted(started) = &event {
                report_peer_version(started.protocol_version.as_deref(), reporter);
            }
            let processed = self.reducer.apply(event, reporter);
            // The reducer's fatal verdicts (history growth, reconcile work bound,
            // patch node-unit ceiling): fatal here.
            if let Some(err) = self.reducer.take_fatal() {
                return Err(err);
            }
            out.push(processed);
        }
        Ok(())
    }

    /// Ends the stream and reports whether it was complete.
    ///
    /// A stream that ended inside a run, or before any run began, is
    /// [`Termination::Truncated`]. Nothing is synthesized for it: open chunk
    /// streams stay open and no `RUN_FINISHED` is invented (TRN-09, LIFE-20).
    ///
    /// This reports only where the run lifecycle stands. It does not say
    /// whether an earlier push was rejected: a stream refused after its
    /// `RUN_FINISHED` still reads `Complete` here. Use
    /// [`finish_checked`](Self::finish_checked) for the verdict of a
    /// processor that may be spent.
    pub fn finish(&mut self) -> Termination {
        match self.verifier.phase() {
            verify::RunPhase::Finished | verify::RunPhase::Failed => Termination::Complete,
            _ => Termination::Truncated,
        }
    }

    /// [`finish`](Self::finish), plus the end-of-stream identity check of a
    /// processor told the requested run ([`expecting`](Self::expecting)):
    /// a complete stream on which the requested run never appeared is a
    /// `verify.identity` error (RUNIN-06). The client ends every run with
    /// this; a host that set no expectation gets exactly `finish`.
    ///
    /// # Errors
    ///
    /// `verify.identity`, as above. The processor is spent afterwards.
    /// A processor already spent by a rejected push fails with that code.
    pub fn finish_checked(&mut self) -> Result<Termination> {
        self.check_live()?;
        let termination = self.finish();
        if termination == Termination::Complete {
            if let Err(err) = self.verifier.finish() {
                self.failed = Some(err.code());
                return Err(err);
            }
        }
        Ok(termination)
    }

    /// Charges what a boundary the host runs before
    /// [`push_value`](Self::push_value) keeps (its
    /// [`retained`](compat::Boundary::retained) figure) with this
    /// processor's id bookkeeping, from the next event on (D28).
    #[cfg(feature = "client")]
    pub(crate) fn charge_boundary(&mut self, bytes: usize) {
        self.external_bookkeeping = bytes;
    }

    /// The reducer's view: history and state so far, borrowed.
    #[must_use]
    pub fn reducer(&self) -> &reduce::Reducer {
        &self.reducer
    }

    /// Takes the reducer, ending the processor.
    #[must_use]
    pub fn into_reducer(self) -> reduce::Reducer {
        self.reducer
    }
}

/// The producer's `RUN_STARTED.protocolVersion`, judged as a consumer: a
/// newer minor, an uninterpretable declaration or another major line is
/// served under the processing model with a warning; the same, an older
/// minor or no declaration passes in silence (VER-21, VER-26, VER-27).
fn report_peer_version(declared: Option<&str>, reporter: &mut Reporter) {
    if declared.is_none() {
        return;
    }
    let peer = crate::version::PeerVersion::classify(declared);
    if let Some(warning) = peer.diagnostic(crate::diagnostics::Scope::Event) {
        reporter.report(|| warning.with_event_type(crate::event::EventType::RunStarted));
    }
}

